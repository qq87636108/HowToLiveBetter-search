def has_hit(hay_ids, expect):
    if expect is None:
        return True  # 宽松：只要求不出错（0 命中也不算 fail，但记录）
    return any(e in hay_ids for e in expect)

def main():
    import json
    idx, syn, kws = load()
    # 门禁与生产同一评分模式（评审 R2：回归门禁须带 df_meta 跑 BM25 模式，与前端口径一致）
    try:
        df_meta = json.load(open("data/df.json", encoding="utf-8"))
    except Exception:
        df_meta = None
    print(f"数据: {len(idx)} 条 | 同义词: {len(syn)} 组 | 条目关键词: {'有' if kws else '无（首版无 keywords.json）'}")
    fails, soft = [], []
    for q, expect in CASES:
        results, terms, frags = search(q, idx, syn, kws, top=10, df_meta=df_meta)
        got = [e['id'] for e in results]
        if not got:
            (soft if expect is None else fails).append((q, "0 命中", expect))
            print(f"  ✗ 「{q}」0 命中（期望 {expect}）")
            continue
        if not has_hit(got[:3], expect):
            # Top3 无正解 → 查 Top10
            if has_hit(got, expect):
                soft.append((q, f"Top3 无正解（Top10 有）got={got[:3]}", expect))
                print(f"  △ 「{q}」Top3 无正解 got={got[:3]} 期望={expect}")
            else:
                fails.append((q, f"Top10 无正解 got={got[:3]}", expect))
                print(f"  ✗ 「{q}」Top10 无正解 got={got[:3]} 期望={expect}")
        else:
            print(f"  ✓ 「{q}」→ {got[:3]}")
    print(f"\n结果: {len(CASES)} 句 | 通过 {len(CASES)-len(fails)-len(soft)} | △ 软警告 {len(soft)} | ✗ 失败 {len(fails)}")
    if fails:
        print("正解率不足 100%，pipeline 门禁拦截")
        sys.exit(1)
    print("回归通过")

if __name__ == '__main__':
    main()
